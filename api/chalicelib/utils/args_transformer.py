# 段代码提供了三个简单的实用函数，用于处理不同类型的参数。这些函数会将输入值转换为特定的数据类型（整数、浮点数或字符串），并为 None 值提供默认处理。


# 功能描述:
# 将输入 x 转换为整数。如果输入 x 为 None，则返回整数 0。
# 应用场景:
# 处理可能为 None 的输入，确保返回值始终为一个整数。
def int_arg(x):
    return int(x) if x is not None else int(0)


# 功能描述:
# 将输入 x 转换为浮点数。如果输入 x 为 None，则返回浮点数 0.0。
# 应用场景:
# 处理可能为 None 的输入，确保返回值始终为一个浮点数。
def float_arg(x):
    return float(x) if x is not None else float(0)


# 功能描述:
# 直接返回输入 x，不进行任何转换。
# 应用场景:
# 当需要一个函数来简单地返回输入值时，这个函数是非常有用的占位符或默认行为。
def string(x):
    return x


# 使用注意事项：
# 数据类型转换:

# int_arg 和 float_arg 假设输入值可以安全地转换为 int 或 float。如果输入值的类型不兼容（例如，传入无法转换为数字的字符串），这些函数将引发异常。
# 默认值处理:

# 这两个函数的默认行为是将 None 值转换为 0 或 0.0。这种设计在处理可能缺少的参数或未定义的输入时非常有用。
# 字符串处理:

# string(x) 函数直接返回输入值 x，所以它可以接受任何类型的输入，完全不做处理。这适用于需要将输入值原样传递的情况。
